const assert = require("node:assert/strict");
const path = require("node:path");

module.exports = async function checkCeoPayroll(page, base, screenshots) {
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + "/payroll-approvals?role=ceo");
  await page.getByRole("heading", { name: "Payroll", exact: true }).waitFor();
  const views = page.getByRole("navigation", { name: "Payroll views", exact: true });
  const records = page.getByRole("region", { name: "Payroll records", exact: true });
  const analytics = page.getByRole("region", { name: "Payroll analytics", exact: true });
  assert.equal(await page.getByRole("navigation", { name: "Payroll sections", exact: true }).count(), 0);
  assert.equal(await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: /Payroll/, exact: false }).getAttribute("href"), "/payroll-approvals");
  assert.equal(await analytics.count(), 0);
  assert.equal(await page.locator(".recharts-surface").count(), 0);
  assert.equal(await records.locator("tbody tr").count(), 5);
  const bounds = await page.locator("h1").boundingBox();
  const tabBounds = await views.boundingBox();
  const summaryBounds = await page.getByRole("region", { name: "Payroll approval summary" }).boundingBox();
  assert.ok(tabBounds.y > bounds.y && tabBounds.y < summaryBounds.y);
  await records.getByRole("button", { name: "Next page", exact: true }).click();
  await views.getByRole("button", { name: "Analytics", exact: true }).click();
  await analytics.locator(".recharts-surface").first().waitFor();
  assert.equal(await records.count(), 0);
  await analytics.getByRole("combobox", { name: "Payroll trend period", exact: true }).selectOption("12");
  assert.equal(await analytics.getByRole("heading", { name: "Payroll period insights", exact: true }).count(), 0);
  assert.equal(await analytics.getByRole("combobox", { name: "Payroll period", exact: true }).count(), 0);
  assert.equal(await analytics.locator(".recharts-surface").count(), 2);
  await views.getByRole("button", { name: "Payroll records", exact: true }).click();
  assert.equal(await page.locator(".recharts-surface").count(), 0);
  assert.equal(await records.getByRole("button", { name: "Page 2", exact: true }).getAttribute("aria-current"), "page");
  const search = records.getByRole("searchbox", { name: "Search payroll reports", exact: true });
  assert.equal(await search.locator("..").locator("svg.lucide-search").count(), 0);
  assert.match(await search.evaluate(element => getComputedStyle(element).backgroundImage), /data:image/);
  await search.fill("Manila");
  assert.match(await records.innerText(), /of 14 payroll runs/);
  await views.getByRole("button", { name: "Analytics", exact: true }).click();
  assert.equal(await analytics.getByRole("combobox", { name: "Payroll trend period", exact: true }).inputValue(), "12");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(screenshots, "ceo-payroll-analytics-desktop.png"), fullPage: true });
  await views.getByRole("button", { name: "Payroll records", exact: true }).click();
  assert.equal(await search.inputValue(), "Manila");
  await records.getByRole("button", { name: "Reset filters", exact: true }).click();
  await records.getByRole("button", { name: /^Pending Review/ }).click();
  assert.equal(await records.locator("tbody tr").count(), 5);
  await records.getByRole("button", { name: /^Review payroll for / }).first().click();
  await page.getByRole("button", { name: "Approve Payroll", exact: true }).click();
  await page.waitForFunction(() => !!window.__approvedPayroll);
  await page.waitForFunction(() => document.querySelector('section[aria-label="Payroll records"]')?.textContent.includes("of 8 payroll runs"));
  assert.equal(await records.locator("tbody tr").count(), 5);
  await records.getByRole("button", { name: "Reset filters", exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(screenshots, "ceo-payroll-records-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  for (const tab of ["Payroll records", "Analytics"]) {
    await views.getByRole("button", { name: tab, exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "CEO payroll " + tab + " mobile overflow");
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.getByRole("heading", { name: "Payroll period insights", exact: true }).count(), 0);
    await page.screenshot({ path: path.join(screenshots, "ceo-payroll-" + tab.replaceAll(" ", "-").toLowerCase() + "-mobile.png"), fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + "/payroll-approvals?role=ceo&view=analytics&runId=payroll-3");
  await page.getByRole("region", { name: "Payroll analytics", exact: true }).waitFor();
  assert.equal(await page.getByRole("combobox", { name: "Payroll period", exact: true }).count(), 0);
  assert.equal(await analytics.locator(".recharts-surface").count(), 2);
};
