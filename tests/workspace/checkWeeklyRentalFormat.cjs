const assert = require('node:assert/strict'), path = require('node:path');
module.exports = async function checkWeeklyRentalFormat(page, base, screenshots) {
  await page.goto(base + '/gmea-rentals/income?weekly-format=1');
  let records = page.getByRole('region', { name: 'Rental records', exact: true });
  await records.getByRole('button', { name: 'Income', exact: true }).click();
  const incomeTableClass = await records.locator('table').getAttribute('class');
  assert.deepEqual(await records.locator('thead').getByRole('columnheader').allTextContents(), ['Company / Location', 'Type', 'Date', 'Amount', 'Payment method']);
  await records.getByRole('button', { name: 'Expense', exact: true }).click();
  const month = records.getByLabel('Filter rental records by month', { exact: true });
  assert.deepEqual(await month.locator('option').allTextContents(), ['All months', 'January 2026']);
  await month.selectOption('2026-01');
  const first = records.getByRole('article', { name: 'Week 2026-01-05 to 2026-01-10', exact: true });
  const last = records.getByRole('article', { name: 'Week 2026-01-26 to 2026-01-31', exact: true });
  const range = records.getByLabel('Select expense week range', { exact: true });
  const navigation = records.getByRole('navigation', { name: 'Expense week pages', exact: true });
  assert.equal(await records.locator('table').count(), 1, 'Only one complete week is rendered per page');
  assert.equal(await last.count(), 0);
  assert.deepEqual(await range.locator('option').allTextContents(), ['Jan 5, 2026 – Jan 10, 2026', 'Jan 26, 2026 – Jan 31, 2026']);
  assert.equal(await navigation.getByRole('button', { name: 'Previous page', exact: true }).isDisabled(), true);
  assert.equal(await records.getByLabel('Weekly date range', { exact: true }).count(), 0, 'No yellow worksheet panel');
  assert.ok((await first.locator('table').getAttribute('class')).startsWith(incomeTableClass), 'Expense reuses the Income table styling');
  assert.deepEqual(await first.locator('thead').getByRole('columnheader').allTextContents(), ['Date', 'Vehicle / Payee', 'Description', 'Amount']);
  assert.equal(await first.locator('[data-label="Payment method"], [data-label="Type"]').count(), 0);
  assert.match(await first.getByRole('heading', { level: 3 }).innerText(), /Jan 5, 2026/);
  assert.match(await first.locator('tbody tr').first().innerText(), /Jan 5, 2026.*Canter.*Diesel.*2,000/s);
  assert.deepEqual(await first.locator('tbody tr').first().locator('td, th').allTextContents(), ['Jan 5, 2026', 'Canter', 'Diesel', '₱2,000.00']);
  assert.deepEqual(await first.locator('tbody tr th button').allTextContents(), ['Canter', 'Bongo', 'Yellow Dump', 'Backhoe XCMG', 'Backhoe Volvo', 'Canter', 'Bongo', 'Canter', 'Backhoe XCMG', 'Bongo', 'REMARK', 'RICHIE', 'DRIVERS', 'OPERATORS', 'DRIVERS', 'OPERATORS']);
  const displayedTotal = (await first.locator('tbody [data-label="Amount"]').allTextContents()).reduce((sum, amount) => sum + Math.round(Number(amount.replace(/[^\d.-]/g, '')) * 100), 0);
  assert.equal(displayedTotal, 5182032, 'The displayed weekly total equals every displayed source row');
  assert.equal(await first.locator('tbody tr').count(), 16, 'All individual expenses for the selected week stay on one page');
  assert.equal(await first.locator('[rowspan]').count(), 0);
  assert.match(await first.innerText(), /Cash Advance/);
  assert.match(await first.innerText(), /REMARK/); assert.match(await first.innerText(), /RICHIE/);
  assert.match(await first.locator('header').innerText(), /51,820\.32/);
  for (const width of [1440, 1280, 1100]) {
    await page.setViewportSize({ width, height: 1100 });
    const controls = [month, range, records.getByLabel('Filter rental records by company', { exact: true }), records.getByLabel('Filter rental records by location', { exact: true }), records.getByRole('button', { name: 'Reset filters', exact: true })];
    const boxes = await Promise.all(controls.map(control => control.boundingBox()));
    assert.ok(boxes.every(box => Math.abs(box.y + box.height - boxes[0].y - boxes[0].height) < 1), `Week range shares the filter row at ${width}px`);
    if (width >= 1280) {
      const search = await records.getByRole('searchbox', { name: 'Search rental records', exact: true }).boundingBox();
      assert.ok(Math.abs(search.y + search.height - boxes[0].y - boxes[0].height) < 1);
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await page.setViewportSize({ width: 1440, height: 1100 });
  await navigation.getByRole('button', { name: 'Next page', exact: true }).click();
  assert.equal(await first.count(), 0);
  assert.equal(await records.locator('table').count(), 1);
  assert.match(await last.locator('header').innerText(), /600\.00/);
  assert.equal(await range.inputValue(), '2026-01:2026-01-26:2026-01-31');
  assert.equal(await navigation.getByRole('button', { name: 'Next page', exact: true }).isDisabled(), true);
  await range.selectOption('2026-01:2026-01-05:2026-01-10');
  assert.equal(await navigation.getByRole('button', { name: 'Page 1', exact: true }).getAttribute('aria-current'), 'page');
  await range.selectOption('2026-01:2026-01-26:2026-01-31');
  await month.selectOption('');
  assert.equal(await first.count(), 1, 'Changing the month resets to the earliest matching week');
  await month.selectOption('2026-01');
  assert.equal(await records.getByLabel('Sort rental records by month', { exact: true }).count(), 0);
  await first.getByRole('button', { name: 'Expense details: Canter, Jan 5, 2026', exact: true }).click();
  let modal = page.getByRole('dialog');
  assert.equal(await modal.getByLabel('Amount *', { exact: true }).inputValue(), '2000');
  assert.equal(await modal.locator('textarea').inputValue(), '');
  await modal.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await records.getByRole('searchbox', { name: 'Search rental records', exact: true }).fill('Canter');
  assert.match(await first.locator('header').innerText(), /6,000\.00/);
  await navigation.getByRole('button', { name: 'Next page', exact: true }).click();
  assert.match(await last.locator('header').innerText(), /500\.00/);
  await records.getByRole('searchbox', { name: 'Search rental records', exact: true }).fill('no matching expense');
  assert.equal(await records.locator('table').count(), 0);
  assert.equal(await range.isDisabled(), true);
  assert.equal(await navigation.count(), 0);
  await records.getByRole('button', { name: 'Reset filters', exact: true }).click();
  await records.getByRole('button', { name: 'Expense', exact: true }).click();
  await month.selectOption('2026-01');
  await page.screenshot({ path: path.join(screenshots, 'rental-january-weekly-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await range.isVisible(), true);
  assert.equal(await first.locator('tbody tr').count(), 16);
  await range.selectOption('2026-01:2026-01-26:2026-01-31');
  assert.equal(await last.locator('tbody tr').count(), 2);
  await navigation.getByRole('button', { name: 'Previous page', exact: true }).click();
  assert.equal(await first.locator('tbody tr').count(), 16);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  for (const table of await records.locator('table').all()) assert.equal(await table.evaluate(element => element.scrollWidth <= element.clientWidth + 1), true);
  await page.screenshot({ path: path.join(screenshots, 'rental-january-weekly-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + '/gmea-rentals/income?weekly-format=1&role=ceo');
  records = page.getByRole('region', { name: 'Rental records', exact: true });
  await records.getByRole('button', { name: 'Expense', exact: true }).click();
  await records.getByRole('button', { name: 'Expense details: Canter, Jan 5, 2026', exact: true }).click();
  modal = page.getByRole('dialog');
  assert.equal(await modal.getByLabel('Amount *', { exact: true }).isDisabled(), true);
  assert.equal(await modal.getByRole('button', { name: 'Save changes', exact: true }).count(), 0);
  await modal.getByRole('button', { name: 'Close dialog', exact: true }).click();
};
