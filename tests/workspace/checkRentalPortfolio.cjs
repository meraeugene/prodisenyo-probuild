const assert = require("node:assert/strict");
const path = require("node:path");

module.exports = async function checkRentalPortfolio(page, base, screenshots) {
  const nav = page.getByRole("navigation", { name: "Main navigation" });
  assert.equal(await nav.getByRole("link", { name: /^(Equipment|Rental Bookings|Operation Expense|Rental Expenses)$/ }).count(), 0);
  const totals = page.getByRole("region", { name: "Overall rental payment and expense totals" });
  await totals.waitFor();
  assert.equal(await page.getByRole("button", { name: /^Rentals(?: \d+)?$/ }).count(), 0);
  assert.equal(await page.locator("table").count(), 1);
  const card = (name) => totals.locator("article").filter({ has: page.getByText(name, { exact: true }) });
  assert.match(await card("Total down payment").innerText(), /15,000\.00/);
  assert.match(await card("Total payment").innerText(), /10,000\.00/);
  assert.match(await card("Total collected").innerText(), /28,000\.00/);
  assert.match(await card("Total expenses").innerText(), /3,580\.00/);
  const locations = page.getByRole("region", { name: "Rental records", exact: true });
  await locations.getByRole("button", { name: "Expense", exact: true }).click();
  assert.equal(await locations.locator("tbody tr").count(), 0);
  assert.match(await locations.innerText(), /No rental expense records to show/);
  assert.match(await card("Total expenses").innerText(), /3,580\.00/);
  await locations.getByRole("button", { name: "Reset filters", exact: true }).click();
  await locations.getByRole("searchbox", { name: "Search rental records" }).fill("Harbor");
  assert.equal(await locations.locator("tbody tr").count(), 3);
  await locations.getByRole("button", { name: "Bayanga", exact: true }).click();
  const details = page.getByRole("region", { name: "Rental location details", exact: true });
  await details.waitFor();
  assert.match(await details.innerText(), /No confirmed receipt/);
  assert.equal(await details.locator("table").count(), 1);
  await details.getByRole("button", { name: "Payment history for Harbor Logistics", exact: true }).click();
  await page.getByRole("dialog").waitFor();
  assert.match(await page.getByRole("dialog").innerText(), /Unconfirmed/);
  assert.match(await page.getByRole("dialog").innerText(), /Historical Excel income record/);
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click();
  await details.getByRole("button", { name: "Expense", exact: true }).click();
  assert.match(await details.innerText(), /No rental expense records to show/);
  await details.getByRole("button", { name: "Back to rentals", exact: true }).click();
  assert.equal(await locations.getByRole("searchbox", { name: "Search rental records" }).inputValue(), "Harbor");
  await locations.getByRole("button", { name: "Manila", exact: true }).first().click();
  assert.match(await details.getByRole("region", { name: "Location payment and expense totals" }).innerText(), /10,000\.00/);
  await details.getByRole("button", { name: "Payment history for Harbor Logistics", exact: true }).first().click();
  assert.match(await page.getByRole("dialog").innerText(), /Down Payment/);
  assert.match(await page.getByRole("dialog").innerText(), /Full Payment/);
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click();
  await page.screenshot({ path: path.join(screenshots, "rental-location-details-desktop.png"), fullPage: true });
  assert.equal(await details.locator("table").count(), 1);
  assert.equal(await details.getByRole("region", { name: "Rental expense records", exact: true }).count(), 0);
  await details.getByRole("button", { name: "Expense", exact: true }).click();
  assert.equal(await details.locator("tbody tr").count(), 0);
  assert.doesNotMatch(await details.innerText(), /Driver salary|Diesel/);
  await details.getByRole("button", { name: "Back to rentals", exact: true }).click();
  await locations.getByRole("searchbox", { name: "Search rental records" }).fill("");
  assert.equal(await locations.locator("table").evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.screenshot({ path: path.join(screenshots, "rental-portfolio-desktop.png"), fullPage: true });
  assert.equal(await page.getByRole("button", { name: "New rental", exact: true }).count(), 0);
  await page.getByRole("button", { name: "Rental income", exact: true }).click();
  await page.getByRole("dialog").waitFor();
  await page.getByRole("dialog").getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await locations.locator("table").evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.evaluate(() => { window.scrollTo(0, 0); });
  await page.screenshot({ path: path.join(screenshots, "rental-single-table-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Rental income", exact: true }).click();
  let modal = page.getByRole("dialog");
  assert.equal(await modal.getByLabel("Income entry", { exact: true }).count(), 0);
  assert.ok((await modal.boundingBox()).width <= 366);
  assert.equal(await modal.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.screenshot({ path: path.join(screenshots, "rental-income-simple-modal-mobile.png"), fullPage: true });
  await modal.getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.getByRole("button", { name: "Rental expense", exact: true }).click();
  assert.equal(await modal.getByLabel("Expense scope *", { exact: true }).count(), 0);
  assert.ok((await modal.boundingBox()).width <= 366);
  assert.equal(await modal.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await page.screenshot({ path: path.join(screenshots, "rental-expense-simple-modal-mobile.png"), fullPage: true });
  await modal.getByRole("button", { name: "Close dialog", exact: true }).click();
  await locations.getByRole("searchbox", { name: "Search rental records" }).fill("Harbor");
  await locations.getByRole("button", { name: "Bayanga", exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(screenshots, "rental-location-details-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + "/gmea-rentals/income?role=ceo");
  await totals.waitFor();
  assert.equal(await page.getByRole("button", { name: /^(New rental|Rental income|Rental expense)$/ }).count(), 0);
  await page.goto(base + "/gmea-rentals/income");
  await totals.waitFor();
};
