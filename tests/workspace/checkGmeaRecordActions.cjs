const assert = require('node:assert/strict'), path = require('node:path');
module.exports = async function checkGmeaRecordActions(page, base, screenshots) {
  const dialog = page.getByRole('dialog'), confirm = page.getByRole('alertdialog');
  const toast = text => page.locator('[data-sonner-toast]').filter({ hasText: text });
  const blue = async () => assert.equal(await dialog.getByRole('button', { name: 'Save and add again', exact: true }).evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(29, 78, 216)');
  await page.goto(base + '/gmea-operation-expenses');
  const report = page.getByRole('region', { name: 'Operation expense reporting', exact: true });
  const totals = page.getByRole('region', { name: 'Operation expense totals', exact: true });
  const count = await page.evaluate(() => window.__operationExpenses.length);
  const amount = Number((await report.locator('tbody tr').first().locator('td').nth(3).innerText()).replace(/[^\d.-]/g, ''));
  await report.getByRole('button', { name: 'Delete', exact: true }).first().click();
  assert.equal(await confirm.getByRole('button', { name: 'Save and add again', exact: true }).count(), 0);
  await confirm.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__operationExpenses.length), count);
  await report.getByRole('button', { name: 'Delete', exact: true }).first().click();
  await confirm.getByRole('button', { name: 'Delete', exact: true }).click();
  await confirm.waitFor({ state: 'hidden' });
  await toast('Operation expense deleted successfully.').waitFor();
  assert.equal(await page.evaluate(() => window.__operationExpenses.length), count - 1);
  assert.ok((await totals.innerText()).includes((550.25 - amount).toFixed(2)));
  await page.getByRole('button', { name: 'New operation expense', exact: true }).click();
  await blue();
  await page.screenshot({ path: path.join(screenshots, 'gmea-blue-repeat-button.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();

  await page.goto(base + '/gmea-rentals/income?weekly-format=1');
  const records = page.getByRole('region', { name: 'Rental records', exact: true });
  await records.getByRole('button', { name: 'Expense', exact: true }).click();
  const week = records.getByRole('article', { name: 'Week 2026-01-05 to 2026-01-10', exact: true });
  await week.getByRole('button', { name: 'Edit', exact: true }).first().click();
  await dialog.getByLabel('Amount *', { exact: true }).fill('2100');
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.match(await week.locator('header').innerText(), /51,920\.32/);
  await week.getByRole('button', { name: 'Delete', exact: true }).first().click();
  await confirm.getByRole('button', { name: 'Delete', exact: true }).click();
  await confirm.waitFor({ state: 'hidden' });
  assert.equal(await week.locator('tbody tr').count(), 15);
  assert.match(await week.locator('header').innerText(), /49,820\.32/);
  assert.match(await week.locator('tbody tr').first().innerText(), /Bongo/);
  await toast('Rental expense deleted successfully.').waitFor();
  await page.screenshot({ path: path.join(screenshots, 'gmea-rental-expense-actions.png'), fullPage: true });

  await page.goto(base + '/gmea-rentals/income');
  const historicalId = await page.evaluate(() => window.__historicalIncome.find(row => row.historical).rental_number);
  await records.getByRole('searchbox').fill(historicalId);
  await records.getByRole('button', { name: 'Edit', exact: true }).first().click();
  await dialog.getByLabel('Company *', { exact: true }).fill('Updated archive customer');
  await dialog.getByLabel('Rental amount', { exact: true }).fill('1000000');
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await toast('Rental income updated successfully.').waitFor();
  assert.match(await records.locator('tbody').innerText(), /Updated archive customer/);
  await records.getByRole('button', { name: 'Delete', exact: true }).first().click();
  await confirm.getByRole('button', { name: 'Delete', exact: true }).click();
  await confirm.waitFor({ state: 'hidden' });
  await toast('Rental income deleted successfully.').waitFor();
  assert.equal(await records.locator('tbody tr').count(), 0);

  await page.goto(base + '/gmea-rentals/bookings');
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click();
  assert.equal(await dialog.getByLabel('Rental service', { exact: true }).getAttribute('readonly'), '');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.ok(await page.getByRole('button', { name: /^Delete rental:/ }).count());
  await page.goto(base + '/gmea-rentals/equipment');
  assert.ok(await page.getByRole('button', { name: /^Delete equipment:/ }).count());
  await page.getByRole('button', { name: /^Edit / }).first().click();
  await blue();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto(base + '/gmea-projects');
  await page.getByRole('button', { name: /^Actions for / }).first().click();
  assert.ok(await page.getByRole('menuitem', { name: /Edit/ }).count());
  assert.ok(await page.getByRole('menuitem', { name: /Delete/ }).count());

  await page.goto(base + '/gmea-rentals/income?role=ceo');
  assert.equal(await records.getByRole('button', { name: /^(Edit|Delete)$/ }).count(), 0);
  await records.getByRole('button', { name: 'Expense', exact: true }).click();
  assert.equal(await records.getByRole('button', { name: /^(Edit|Delete)$/ }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.goto(base + '/gmea-operation-expenses?role=ceo');
  assert.equal(await report.getByRole('button', { name: /^(Edit|Delete)$/ }).count(), 0);
};
