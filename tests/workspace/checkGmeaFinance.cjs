const assert = require("node:assert/strict");
const path = require("node:path");

module.exports = async function checkGmeaFinance(page, base, screenshots) {
  await page.goto(base + "/gmea-rentals/income");
  assert.equal(await page.getByRole("button", { name: "New rental", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: /^(Monthly|Weekly)$/ }).count(), 0);
  const incomeTable = page.getByRole("region", { name: "Rental records", exact: true });
  assert.equal(await page.locator("table").count(), 1);
  assert.equal(await incomeTable.getByRole("columnheader").count(), 6);
  assert.equal(await incomeTable.locator("table").evaluate(element => element.scrollWidth <= element.clientWidth), true);
  assert.doesNotMatch(await incomeTable.innerText(), /Receipts appear separately/);
  for (const name of ["Company / Location", "Type", "Date", "Amount", "Payment method"])
    assert.equal(await incomeTable.getByRole("columnheader", { name, exact: true }).count(), 1);
  await incomeTable.getByLabel("Filter rental records by payment type", { exact: true }).selectOption("down_payment");
  assert.equal(await incomeTable.locator("tbody tr").count(), 2);
  await incomeTable.getByLabel("Filter rental records by location", { exact: true }).selectOption("manila");
  assert.equal(await incomeTable.locator("tbody tr").count(), 1);
  await incomeTable.getByRole("button", { name: "Reset filters", exact: true }).click();
  assert.equal(await incomeTable.getByLabel("Filter rental records by location", { exact: true }).inputValue(), "");
  await incomeTable.getByRole("button", { name: "Expense", exact: true }).click();
  assert.equal(await incomeTable.getByRole("button", { name: /^Expense details:/ }).count(), 1);
  await incomeTable.getByLabel("Select expense week range", { exact: true }).selectOption("2026-10:2026-10-05:2026-10-10");
  assert.equal(await incomeTable.getByRole("button", { name: /^Expense details:/ }).count(), 3);
  assert.match(await incomeTable.innerText(), /Driver salary|Diesel/);
  assert.equal(await page.evaluate(() => window.__rentalOperations.expenses.length), 4);
  await incomeTable.getByRole("button", { name: "Income", exact: true }).click();
  assert.equal(await incomeTable.locator("tbody tr").count(), 5);
  await incomeTable.getByRole("button", { name: "Reset filters", exact: true }).click();
  await page.getByRole("button", { name: "Rental income", exact: true }).click();
  let dialog = page.getByRole("dialog");
  assert.equal(await dialog.getByLabel("Income entry", { exact: true }).count(), 0);
  assert.equal(await dialog.locator("datalist").count(), 0);
  assert.ok((await dialog.boundingBox()).width <= 640);
  await dialog.getByRole("button", { name: "Save income", exact: true }).click();
  await dialog.getByRole("alert").waitFor();
  await dialog.getByLabel("Company name *", { exact: true }).fill("Demo Hire");
  await dialog.getByLabel("Location *", { exact: true }).fill("Gusa");
  await dialog.getByLabel("Rental service", { exact: true }).fill("Backhoe rental");
  await dialog.getByLabel("Total amount *", { exact: true }).fill("1000");
  await dialog.getByLabel("Down payment", { exact: true }).fill("250");
  await dialog.getByLabel("Down payment date", { exact: true }).fill("2026-05-01");
  await dialog.getByLabel("Mode of payment *", { exact: true }).fill("Cash");
  await page.getByRole("option", { name: "Cash", exact: true }).click();
  await page.screenshot({ path: path.join(screenshots, "rental-income-simple-modal.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Save income", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  const incomeId = await page.evaluate(() => window.__savedIncomeInput.id);
  const locations = incomeTable;
  await locations.getByRole("searchbox").fill("Demo Hire");
  await locations.getByRole("button", { name: "Gusa", exact: true }).first().waitFor();
  await locations.getByRole("button", { name: "Payment history for Demo Hire", exact: true }).click();
  assert.match(await dialog.innerText(), /750\.00/);
  await dialog.getByRole("button", { name: "Add payment", exact: true }).click();
  assert.equal(await dialog.getByLabel("Income entry", { exact: true }).count(), 0);
  assert.equal(await dialog.getByLabel("Total amount *", { exact: true }).getAttribute("readonly"), "");
  await dialog.getByLabel("Full payment", { exact: true }).fill("750");
  await dialog.getByLabel("Full payment date", { exact: true }).fill("2026-05-09");
  await dialog.getByLabel("Mode of payment *", { exact: true }).fill("GCash");
  await dialog.getByLabel("Mode of payment *", { exact: true }).press("ArrowDown");
  await dialog.getByLabel("Mode of payment *", { exact: true }).press("Enter");
  await dialog.getByRole("button", { name: "Save income", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.waitForFunction(() => window.__savedIncomeInput.version === 1);
  await page.getByRole("button", { name: "Rental expense", exact: true }).click();
  assert.equal(await dialog.getByLabel("Related rental / location", { exact: true }).count(), 0);
  assert.equal(await dialog.getByLabel("Expense scope *", { exact: true }).count(), 0);
  assert.equal(await dialog.locator("datalist").count(), 0);
  assert.ok((await dialog.boundingBox()).width <= 640);
  await dialog.getByLabel("Description *", { exact: true }).fill("Gusa rental fuel");
  await dialog.getByLabel("Date *", { exact: true }).fill("2026-05-10");
  await dialog.getByLabel("Supplier / payee", { exact: true }).fill("Opera");
  await page.getByRole("option", { name: "Operators", exact: true }).click();
  assert.equal(await dialog.getByLabel("Supplier / payee name *", { exact: true }).count(), 0);
  await dialog.getByLabel("Payment method", { exact: true }).fill("Cash");
  await page.getByRole("option", { name: "Cash", exact: true }).click();
  await dialog.getByLabel("Amount *", { exact: true }).fill("50");
  await page.screenshot({ path: path.join(screenshots, "rental-expense-simple-modal.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Add expense", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => window.__savedRentalExpense.rental_id), null);
  assert.equal(await page.evaluate(() => window.__savedRentalExpense.supplier), "Operators");
  assert.equal(await page.evaluate(() => window.__savedRentalExpense.method), "Cash");
  assert.equal(await page.evaluate(() => window.__savedIncomeInput.id), incomeId);
  await locations.getByRole("button", { name: "Gusa", exact: true }).first().click();
  const details = page.getByRole("region", { name: "Rental location details" });
  await details.getByRole("button", { name: "Payment history for Demo Hire", exact: true }).first().click();
  assert.match(await dialog.innerText(), /250\.00/);
  assert.match(await dialog.innerText(), /750\.00/);
  assert.equal(await dialog.getByRole("link", { name: "Open rental details", exact: true }).count(), 0);
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  assert.equal(await details.locator("table").count(), 1);
  await details.getByRole("button", { name: "Expense", exact: true }).click();
  assert.equal(await details.locator("tbody tr").count(), 0);
  assert.doesNotMatch(await details.innerText(), /Gusa rental fuel/);
  assert.equal(await page.evaluate(() => window.__rentalOperations.expenses.length), 5);
  await page.screenshot({ path: path.join(screenshots, "rental-income-and-expense-entry.png"), fullPage: true });
  await page.goto(base + "/gmea-operation-expenses");
  await page.getByRole("heading", { name: "Operation Expenses", exact: true }).waitFor();
  const report = page.getByRole("region", { name: "Operation expense reporting" });
  const totals = page.getByRole("region", { name: "Operation expense totals" });
  assert.equal(await report.evaluate(element => getComputedStyle(element).paddingLeft), "0px");
  assert.match(await totals.innerText(), /550\.25/);
  assert.equal(await report.locator("tbody tr").count(), 3);
  await page.getByRole("button", { name: "Analytics", exact: true }).click();
  assert.match(await totals.innerText(), /550\.25/);
  const charts = page.getByRole("region", { name: "Operation expense charts", exact: true });
  assert.equal(await charts.locator(".recharts-surface").count(), 2);
  await charts.getByText("View trend data", { exact: true }).click();
  assert.match(await charts.locator("figure").first().locator("tbody").innerText(), /150\.25/);
  assert.match(await charts.locator("figure").first().locator("tbody").innerText(), /400\.00/);
  await charts.getByText("View trend data", { exact: true }).click();
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-monthly-charts.png"), fullPage: true });
  await report.getByRole("button", { name: "Weekly", exact: true }).click();
  await report.getByLabel("Date in operation expense week", { exact: true }).fill("2026-10-01");
  assert.match(await totals.innerText(), /550\.40/);
  assert.equal(await charts.getByText("Weekly expenses by day", { exact: true }).count(), 1);
  await charts.getByText("View trend data", { exact: true }).click();
  assert.equal(await charts.locator("figure").first().locator("tbody tr").count(), 7);
  assert.match(await charts.locator("figure").first().locator("tbody").innerText(), /100\.15/);
  await charts.getByText("View trend data", { exact: true }).click();
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-weekly-charts.png"), fullPage: true });
  await page.getByRole("button", { name: "Expenses", exact: true }).click();
  assert.equal(await report.locator("tbody tr").count(), 4);
  await report.getByRole("button", { name: "Monthly", exact: true }).click();
  await report.getByLabel("Operation expense month", { exact: true }).fill("2026-10");
  await page.getByRole("button", { name: "New operation expense", exact: true }).click();
  assert.ok((await dialog.boundingBox()).width <= 640);
  await page.screenshot({ path: path.join(screenshots, "operation-expense-compact-modal.png"), fullPage: true });
  await dialog.getByLabel("Date *", { exact: true }).fill("2026-10-10");
  await dialog.getByLabel("Category *", { exact: true }).selectOption("Transportation");
  await dialog.getByLabel("Description *", { exact: true }).fill("Office travel");
  await dialog.getByLabel("Amount *", { exact: true }).fill("25");
  await dialog.getByRole("button", { name: "Save expense", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.waitForFunction(() => window.__savedOperationExpense?.amount === 25);
  assert.match(await totals.innerText(), /575\.25/);
  await report.getByRole("searchbox", { name: "Search operation expenses", exact: true }).fill("Office travel");
  assert.equal(await report.locator("tbody tr").count(), 1);
  await report.getByRole("button", { name: "Edit", exact: true }).click();
  await dialog.getByLabel("Amount *", { exact: true }).fill("30");
  await dialog.getByRole("button", { name: "Save expense", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.match(await totals.innerText(), /580\.25/);
  assert.equal(await report.getByRole("searchbox", { name: "Search operation expenses", exact: true }).inputValue(), "");
  assert.equal(await report.getByRole("button", { name: "Reset filters", exact: true }).isDisabled(), true);
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Analytics", exact: true }).click();
  await charts.locator(".recharts-surface").first().waitFor();
  assert.equal(await charts.locator(".recharts-surface").count(), 2);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.evaluate(() => { window.scrollTo(0, 0); });
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-monthly-charts-mobile.png"), fullPage: true });
  await report.getByRole("button", { name: "Weekly", exact: true }).click();
  await report.getByLabel("Date in operation expense week", { exact: true }).fill("2026-10-01");
  assert.match(await totals.innerText(), /550\.40/);
  assert.equal(await charts.locator(".recharts-surface").count(), 2);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(screenshots, "operation-expenses-weekly-charts-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + "/gmea-operation-expenses?role=ceo");
  await report.waitFor();
  assert.equal(await page.getByRole("button", { name: "New operation expense", exact: true }).count(), 0);
  await report.getByRole("button", { name: "Details", exact: true }).first().click();
  assert.equal(await dialog.getByLabel("Amount *", { exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole("button", { name: "Save expense", exact: true }).count(), 0);
  await dialog.getByRole("button", { name: "Close dialog", exact: true }).click();
  await require("./checkGmeaSavedInputs.cjs")(page, base, screenshots);
  await require("./checkGmeaDashboard.cjs")(page, base, screenshots);
};
